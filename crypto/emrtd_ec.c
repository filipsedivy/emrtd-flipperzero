/*
 * Load a point from its uncompressed encoding without going through
 * mbedtls_ecp_point_read_binary().
 *
 * That function also accepts the compressed forms 02 and 03, and recovering
 * the missing coordinate means taking a modular square root - which reaches
 * mbedtls_mpi_exp_mod(), whose Montgomery multiplication depends on
 * mbedtls_ct_memcpy_if(). That symbol is not in the firmware's mbed TLS
 * archive and is not exported by the firmware either, so merely linking the
 * decompression path makes the application unloadable. See docs/platform.md.
 *
 * ICAO 9303-11 mandates the uncompressed encoding of TR-03111, so nothing is
 * lost: the coordinates are handed over as hex through the one public entry
 * point that assigns them directly.
 */
static int emrtd_ec_point_load_xy(
    mbedtls_ecp_point* point,
    const uint8_t* x,
    const uint8_t* y,
    size_t size) {
    char x_hex[2 * EMRTD_EC_COORD_MAX + 1];
    char y_hex[2 * EMRTD_EC_COORD_MAX + 1];
    static const char digits[] = "0123456789ABCDEF";

    if(size > EMRTD_EC_COORD_MAX) {
        return MBEDTLS_ERR_ECP_BAD_INPUT_DATA;
    }
    for(size_t i = 0; i < size; i++) {
        x_hex[2 * i] = digits[x[i] >> 4];
        x_hex[2 * i + 1] = digits[x[i] & 0x0F];
        y_hex[2 * i] = digits[y[i] >> 4];
        y_hex[2 * i + 1] = digits[y[i] & 0x0F];
    }
    x_hex[2 * size] = '\0';
    y_hex[2 * size] = '\0';

    return mbedtls_ecp_point_read_string(point, 16, x_hex, y_hex);
}

