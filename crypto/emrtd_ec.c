bool emrtd_ec_curve_supported(const EmrtdCurve* curve) {
    return curve != NULL && curve->bits <= MBEDTLS_ECP_MAX_BITS;
}

int emrtd_ec_group_load(mbedtls_ecp_group* grp, const EmrtdCurve* curve) {
    if(grp == NULL || !emrtd_ec_curve_supported(curve)) {
        return MBEDTLS_ERR_ECP_BAD_INPUT_DATA;
    }

    int ret;
    mbedtls_ecp_group_init(grp);

    /*
     * MBEDTLS_ECP_DP_NONE keeps mbed TLS from assuming one of its built in
     * curves; grp->modp stays NULL, which selects the generic modular
     * reduction. The cofactor is deliberately left at the zero set by
     * mbedtls_ecp_group_init(): mbedtls_ecp_group_free() only releases the
     * parameter MPIs when it is not one, and ours are heap allocated. The
     * field takes no part in the arithmetic (ecp.c reads it only there).
     */
    grp->id = MBEDTLS_ECP_DP_NONE;

    if((ret = mbedtls_mpi_read_binary(&grp->P, curve->p, curve->size)) != 0) goto fail;
    if((ret = mbedtls_mpi_read_binary(&grp->A, curve->a, curve->size)) != 0) goto fail;
    if((ret = mbedtls_mpi_read_binary(&grp->B, curve->b, curve->size)) != 0) goto fail;
    if((ret = mbedtls_mpi_read_binary(&grp->N, curve->n, curve->size)) != 0) goto fail;

    grp->pbits = mbedtls_mpi_bitlen(&grp->P);
    grp->nbits = mbedtls_mpi_bitlen(&grp->N);

    /*
     * The coordinates of an mbedtls_ecp_point are private in mbed TLS 3, so
     * the generator is assigned through the one public call that takes them
     * directly. See emrtd_ec_point_load_xy() for why the binary reader is
     * avoided throughout this file.
     */
    if((ret = emrtd_ec_point_load_xy(&grp->G, curve->gx, curve->gy, curve->size)) != 0) {
        goto fail;
    }

    return 0;

fail:
    mbedtls_ecp_group_free(grp);
    return ret;
}

int emrtd_ec_point_read(
    mbedtls_ecp_group* grp,
    mbedtls_ecp_point* point,
    const uint8_t* data,
    size_t len) {
    if(len < 1 || data[0] != 0x04) {
        /* ICAO 9303-11 mandates the uncompressed encoding of TR-03111. */
        return MBEDTLS_ERR_ECP_FEATURE_UNAVAILABLE;
    }
    const size_t size = (mbedtls_mpi_bitlen(&grp->P) + 7) / 8;
    if(len != 1 + 2 * size) {
        return MBEDTLS_ERR_ECP_BAD_INPUT_DATA;
    }

    int ret = emrtd_ec_point_load_xy(point, data + 1, data + 1 + size, size);
    if(ret != 0) {
        return ret;
    }
    /* A point off the curve would leak the private scalar, so refuse it. */
    return mbedtls_ecp_check_pubkey(grp, point);
}

int emrtd_ec_point_write(
    const mbedtls_ecp_group* grp,
    const mbedtls_ecp_point* point,
    uint8_t* out,
    size_t out_size,
    size_t* out_len) {
    return mbedtls_ecp_point_write_binary(
        grp, point, MBEDTLS_ECP_PF_UNCOMPRESSED, out_len, out, out_size);
}

